HIGHWAY_META = {
    "gyeongbu":  ("경부고속도로",   416.0),
    "yeongdong": ("영동고속도로",   234.4),
    "seohaeAN":  ("서해안고속도로", 340.4),
}


class Command(BaseCommand):
    help = "3대 고속도로(경부/영동/서해안) 노드(IC/RA) 시퀀스 데이터를 DB에 로드합니다."

    def add_arguments(self, parser):
        parser.add_argument('--highway',   type=str, default=None,
                            help='특정 노선만 (gyeongbu / seohaeAN / yeongdong)')
        parser.add_argument('--direction', type=str, default=None,
                            help='특정 방향만 (UP / DOWN)')
        parser.add_argument('--clear',     action='store_true',
                            help='로드 전 기존 노드 삭제')

    def handle(self, *args, **options):
        hw_filter  = options.get('highway')
        dir_filter = (options.get('direction') or '').upper() or None
        do_clear   = options.get('clear')

        # ── Highway upsert ──────────────────────
        for code, (name, dist) in HIGHWAY_META.items():
            Highway.objects.update_or_create(
                code=code,
                defaults={'name': name, 'total_distance_km': dist},
            )
        self.stdout.write('✅ Highway 기본 데이터 준비 완료')

        total_loaded = 0

        for (hw_code, direction), dataset in ALL_DATASETS.items():
            if hw_filter and hw_filter != hw_code:
                continue
            if dir_filter and dir_filter != direction:
                continue

            highway = Highway.objects.get(code=hw_code)

            if do_clear:
                deleted, _ = HighwayNode.objects.filter(
                    highway=highway, direction=direction
                ).delete()
                self.stdout.write(f'🗑  기존 노드 {deleted}개 삭제 ({hw_code} {direction})')

            created_count = 0
            for seq, ntype, name, lat, lng, dist in dataset:
                _, created = HighwayNode.objects.update_or_create(
                    highway=highway,
                    direction=direction,
                    sequence=seq,
                    defaults={
                        'node_type':              ntype,
                        'name':                   name,
                        'latitude':               lat,
                        'longitude':              lng,
                        'distance_from_start_km': dist,
                        'is_active':              True,
                    },
                )
                if created:
                    created_count += 1

            total_loaded += len(dataset)
            ic_cnt = sum(1 for r in dataset if r[1] == 'IC')
            ra_cnt = sum(1 for r in dataset if r[1] == 'RA')
            self.stdout.write(self.style.SUCCESS(
                f'✅ {highway.name} {direction}: '
                f'{len(dataset)}개 로드 (IC {ic_cnt} / RA {ra_cnt} / 신규 {created_count}개)'
            ))

        self.stdout.write(self.style.SUCCESS(
            f'\n🎉 총 {total_loaded}개 노드 로드 완료!'
        ))
